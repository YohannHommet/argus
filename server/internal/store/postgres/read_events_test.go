// TestGetEvent_IndexScanOnSinglePartition verifies SPEC §2.5's AC: GetEvent's
// (ts, seq) PK lookup shows an Index Scan touching exactly one partition
// (review M2: there is no events.id index, so a uuid lookup would have been
// a full scan of every partition). Asserted on EXPLAIN plan text per the
// ticket note (P3-02's equivalent AC used pg_stat_user_indexes deltas
// instead, but this AC explicitly names EXPLAIN and "one partition").
func TestGetEvent_IndexScanOnSinglePartition(t *testing.T) {
	st, pool := newStore(t)
	sessionID := nextTestSessionID("explain-getevent")
	seedSession(t, pool, sessionSeed{ID: sessionID})

	months := []time.Time{
		time.Date(2025, 3, 1, 0, 0, 0, 0, time.UTC),
		time.Date(2025, 4, 1, 0, 0, 0, 0, time.UTC),
		time.Date(2025, 5, 1, 0, 0, 0, 0, time.UTC),
	}
	require.NoError(t, st.EnsurePartitions(context.Background(), months[0], months[len(months)-1]))

	const perMonth = 4000
	seq := int64(7000)
	var targetTS time.Time
	var targetSeq int64
	var seeds []eventSeed
	for _, month := range months {
		for i := 0; i < perMonth; i++ {
			seq++
			ts := month.Add(time.Duration(i) * time.Second)
			seeds = append(seeds, eventSeed{Seq: seq, SessionID: sessionID, TS: ts, Kind: "tool.pre"})
			if month.Equal(months[1]) && i == perMonth/2 {
				targetTS, targetSeq = ts, seq
			}
		}
	}
	seedFullEventsBulk(t, pool, seeds)
	require.False(t, targetTS.IsZero(), "target row must have been seeded")
	_, err := pool.Exec(context.Background(), "ANALYZE events")
	require.NoError(t, err)

	rows, err := pool.Query(context.Background(),
		"EXPLAIN SELECT seq, id, ts FROM events WHERE ts = $1 AND seq = $2", targetTS, targetSeq)
	require.NoError(t, err)
	defer rows.Close()

	var planLines []string
	for rows.Next() {
		var line string
		require.NoError(t, rows.Scan(&line))
		planLines = append(planLines, line)
	}
	require.NoError(t, rows.Err())
	plan := fmt.Sprintf("%v", planLines)

	require.Contains(t, plan, "Index Scan", "GetEvent's (ts, seq) PK lookup must use an Index Scan, not a Seq Scan")

	expectedPartition := fmt.Sprintf("events_%04d_%02d", months[1].Year(), months[1].Month())
	require.Contains(t, plan, expectedPartition, "the plan must reference the single partition containing ts")
	for _, month := range []time.Time{months[0], months[2]} {
		other := fmt.Sprintf("events_%04d_%02d", month.Year(), month.Month())
		require.NotContainsf(t, plan, other, "partition pruning must exclude %s — only one partition should be touched", other)
	}
}

// TestListEvents_SessionTimeline_IndexScanWithPartitionPruning verifies SPEC
// §2.5's AC for the session timeline: an index scan on
// `events_*(session_id, ts, seq)` with partition pruning. Built from the
// exact filter/page ListEvents itself uses (store.EventFilter.SessionID),
// EXPLAINed directly rather than through the store method, since Store
// exposes no EXPLAIN hook.
func TestListEvents_SessionTimeline_IndexScanWithPartitionPruning(t *testing.T) {
	st, pool := newStore(t)
	sessionID := nextTestSessionID("explain-timeline")
	seedSession(t, pool, sessionSeed{ID: sessionID})

	month := time.Date(2025, 9, 1, 0, 0, 0, 0, time.UTC)
	require.NoError(t, st.EnsurePartitions(context.Background(), month, month))

	// Many OTHER sessions interleave with `sessionID` at a realistic
	// fan-out (SPEC §2.4's partition holds every session active that
	// month): sessionID's rows are only 1/50th of the partition, sparse
	// and scattered through the whole ts range, so a full-partition scan
	// riding the (ts, seq) PK — cheap when a target session's share is
	// large enough that ts order alone gets you to LIMIT quickly — is no
	// longer the planner's best option; the selective (session_id, ts,
	// seq) index is.
	const n = 20000
	const fanOut = 50
	seq := int64(8000)
	var seeds []eventSeed
	for i := 0; i < n; i++ {
		seq++
		ts := month.Add(time.Duration(i) * time.Second)
		sid := sessionID
		if i%fanOut != 0 {
			sid = fmt.Sprintf("explain-timeline-other-%d", i%fanOut)
		}
		seeds = append(seeds, eventSeed{Seq: seq, SessionID: sid, TS: ts, Kind: "tool.pre", VendorSeq: ptrInt64(int64(i))})
	}
	seedFullEventsBulk(t, pool, seeds)
	_, err := pool.Exec(context.Background(), "ANALYZE events")
	require.NoError(t, err)

	explainSQL := "EXPLAIN SELECT e.seq FROM events e WHERE e.session_id = $1 ORDER BY e.ts ASC, e.vendor_seq ASC NULLS LAST, e.seq ASC LIMIT 51"
	rows, err := pool.Query(context.Background(), explainSQL, sessionID)
	require.NoError(t, err)
	defer rows.Close()

	var planLines []string
	for rows.Next() {
		var line string
		require.NoError(t, rows.Scan(&line))
		planLines = append(planLines, line)
	}
	require.NoError(t, rows.Err())
	plan := fmt.Sprintf("%v", planLines)

	require.Contains(t, plan, "Index Scan", "the session timeline must use an Index Scan")
	expectedIndex := fmt.Sprintf("events_%04d_%02d_session_ts_seq_idx", month.Year(), month.Month())
	require.Contains(t, plan, expectedIndex, "the session timeline must ride the (session_id, ts, seq) index")
}

