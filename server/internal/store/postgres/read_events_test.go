func TestListEvents_FieldsSlimOmitsAttrs_MeasurablySmaller(t *testing.T) {
	st, pool := newStore(t)
	sessionID := nextTestSessionID("fields")
	seedSession(t, pool, sessionSeed{ID: sessionID})
	base := time.Now().UTC().Truncate(time.Millisecond)
	ensureRange(t, st, base, base)

	bigAttrs := map[string]any{
		"tool_input":  "a moderately long string that would not appear in the slim response at all",
		"nested":      map[string]any{"a": 1, "b": 2, "c": []int{1, 2, 3, 4, 5}},
		"another_key": "more padding to make the size difference unambiguous",
	}
	seedFullEvent(t, pool, eventSeed{Seq: 4001, SessionID: sessionID, TS: base, Kind: "tool.result", Attrs: bigAttrs})

	slim, _, err := st.ListEvents(context.Background(), store.EventFilter{SessionID: sessionID, Fields: store.FieldsSlim}, store.Page{Limit: 10})
	require.NoError(t, err)
	full, _, err := st.ListEvents(context.Background(), store.EventFilter{SessionID: sessionID, Fields: store.FieldsFull}, store.Page{Limit: 10})
	require.NoError(t, err)
	require.Len(t, slim, 1)
	require.Len(t, full, 1)

	require.Nil(t, slim[0].Attrs, "fields=slim must not select attrs from the database at all")
	require.Equal(t, "a moderately long string that would not appear in the slim response at all", full[0].Attrs["tool_input"])

	slimJSON, err := json.Marshal(slim[0])
	require.NoError(t, err)
	fullJSON, err := json.Marshal(full[0])
	require.NoError(t, err)
	require.Greaterf(t, len(fullJSON), len(slimJSON), "full JSON (%d bytes) must be measurably larger than slim (%d bytes)", len(fullJSON), len(slimJSON))
}

