// --- GetEvent nullable-field round-trip -------------------------------------

func TestGetEvent_NullableNumericAndBooleanFields(t *testing.T) {
	st, pool := newStore(t)
	sessionID := nextTestSessionID("getevent-numeric")
	seedSession(t, pool, sessionSeed{ID: sessionID})
	ts := time.Now().UTC().Truncate(time.Millisecond)
	ensureRange(t, st, ts, ts)

	seedFullEvent(t, pool, eventSeed{Seq: 14001, SessionID: sessionID, TS: ts, Kind: "llm.request", VendorSeq: ptrInt64(7)})
	_, err := pool.Exec(context.Background(), `
		UPDATE events SET input_tokens = 100, output_tokens = 50, cost_usd = 1.23456789, success = true
		WHERE seq = 14001`)
	require.NoError(t, err)

	got, err := st.GetEvent(context.Background(), model.EventRef{TS: ts, Seq: 14001})
	require.NoError(t, err)
	require.NotNil(t, got.VendorSeq)
	require.Equal(t, int64(7), *got.VendorSeq)
	require.NotNil(t, got.InputTokens)
	require.Equal(t, int64(100), *got.InputTokens)
	require.NotNil(t, got.CostUSD)
	require.InDelta(t, 1.23456789, *got.CostUSD, 0.0000001)
	require.NotNil(t, got.Success)
	require.True(t, *got.Success)

	// A second row with everything left NULL exercises the nil branches of
	// int8OrNil/boolOrNil/CostUSD alongside the first row's non-nil ones.
	seedFullEvent(t, pool, eventSeed{Seq: 14002, SessionID: sessionID, TS: ts.Add(time.Second), Kind: "tool.pre"})
	ensureRange(t, st, ts.Add(time.Second), ts.Add(time.Second))
	got2, err := st.GetEvent(context.Background(), model.EventRef{TS: ts.Add(time.Second), Seq: 14002})
	require.NoError(t, err)
	require.Nil(t, got2.VendorSeq)
	require.Nil(t, got2.InputTokens)
	require.Nil(t, got2.CostUSD)
	require.Nil(t, got2.Success)
}
