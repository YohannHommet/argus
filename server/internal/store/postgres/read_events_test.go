func TestListEvents_KeysetAcrossPartitionBoundary_EveryRowExactlyOnce(t *testing.T) {
	st, pool := newStore(t)
	sessionID := nextTestSessionID("xpart")
	seedSession(t, pool, sessionSeed{ID: sessionID})

	monthA := time.Date(2025, 6, 1, 0, 0, 0, 0, time.UTC)
	monthB := time.Date(2025, 7, 1, 0, 0, 0, 0, time.UTC)
	require.NoError(t, st.EnsurePartitions(context.Background(), monthA, monthB))

	const perMonth = 15
	expected := map[int64]struct{}{}
	seq := int64(5000)
	for i := 0; i < perMonth; i++ {
		seq++
		ts := monthA.Add(time.Duration(i) * time.Hour)
		seedFullEvent(t, pool, eventSeed{Seq: seq, SessionID: sessionID, TS: ts, Kind: "tool.pre", VendorSeq: ptrInt64(int64(i))})
		expected[seq] = struct{}{}
	}
	for i := 0; i < perMonth; i++ {
		seq++
		ts := monthB.Add(time.Duration(i) * time.Hour)
		seedFullEvent(t, pool, eventSeed{Seq: seq, SessionID: sessionID, TS: ts, Kind: "tool.pre", VendorSeq: ptrInt64(int64(i))})
		expected[seq] = struct{}{}
	}

	seen := map[int64]int{}
	var cursor store.Cursor
	pages := 0
	for {
		pages++
		require.Lessf(t, pages, 20, "too many pages — pagination is likely looping")
		got, next, err := st.ListEvents(context.Background(), store.EventFilter{SessionID: sessionID}, store.Page{Limit: 4, Cursor: cursor})
		require.NoError(t, err)
		for _, e := range got {
			seen[e.Seq]++
		}
		if next == "" {
			break
		}
		cursor = next
	}

	require.Len(t, seen, len(expected), "every seeded row must be returned")
	for seqVal := range expected {
		require.Equalf(t, 1, seen[seqVal], "seq %d must be returned exactly once, got %d", seqVal, seen[seqVal])
	}
}

