func TestListEvents_IdenticalTS_OrdersByVendorSeqNotSeq(t *testing.T) {
	st, pool := newStore(t)
	sessionID := nextTestSessionID("tie")
	seedSession(t, pool, sessionSeed{ID: sessionID})
	base := time.Now().UTC().Truncate(time.Millisecond)
	ensureRange(t, st, base, base)

	// seq is HIGHER for the row whose vendor_seq is LOWER: a (ts, seq)-only
	// keyset/sort would get this backwards (SPEC §1.2's "ordering is exactly
	// (ts, vendor_seq NULLS LAST, seq)" AC).
	seedFullEvent(t, pool, eventSeed{Seq: 1001, SessionID: sessionID, TS: base, Kind: "tool.decision", VendorSeq: ptrInt64(5)})
	seedFullEvent(t, pool, eventSeed{Seq: 1002, SessionID: sessionID, TS: base, Kind: "tool.decision", VendorSeq: ptrInt64(3)})

	got, _, err := st.ListEvents(context.Background(), store.EventFilter{SessionID: sessionID}, store.Page{Limit: 10})
	require.NoError(t, err)
	require.Len(t, got, 2)
	require.Equal(t, int64(1002), got[0].Seq, "vendor_seq=3 must come first even though its seq (1002) is larger")
	require.Equal(t, int64(1001), got[1].Seq)
}

