// Package postgres — rollups.go implements store.Maintenance.RunRollups,
// the SPEC §2.4 rollup job: single-flighted via a transaction-scoped
// advisory lock, claiming dirty (bucket, source) pairs from rollup_dirty
// plus the current/previous hour unconditionally, then a full per-bucket
// recompute of rollup_hourly for source='event' and source='metric'
// separately (SPEC §1.8: never summed), followed by a rollup_daily
// recompute for every affected day — all inside the one transaction RunRollups
// opens, so a failure at any step restores rollup_dirty for the next run.
//
// # Why there is no events.seq watermark (SPEC §2.4, review blocker B4)
//
// events.seq is allocated by `GENERATED BY DEFAULT AS IDENTITY` at INSERT
// time, before commit. Two concurrent WriteBatch transactions can allocate
// seq in one order and commit in the other (the slower transaction holds
// the lower seq but commits last). A job that tracked "the highest seq
// processed so far" and only looked at events.seq > watermark on the next
// run would permanently miss the low-seq transaction's rows: by the time it
// commits, the watermark has already moved past its seq. rollup_dirty has
// no such window because the dirty mark is written by markRollupDirty
// (dirty.go) inside the *same* transaction as the events insert — the mark
// and the data it describes become visible atomically together, however
// late that transaction commits relative to any other. RunRollups's claim
// step (ClaimDirtyBuckets) reads rollup_dirty, never events.seq, and that is
// the whole mechanism; see rollups_test.go's B4 test for the concurrency
// scenario this design survives and a seq watermark would not.
package postgres

